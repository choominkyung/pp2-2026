# 문제: random 모듈에 있는 함수를 사용하여서 7개의 단어 중에서 랜덤하게 3개를 선택하여 출력하여 보자.
# 설계:
# - random 모듈을 임포트한다.
# - 7개의 단어가 포함된 리스트를 생성한다.
# - random.sample() 함수를 사용하여 리스트에서 중복 없이 무작위로 3개의 단어를 선택한다.
# - 선택된 단어들을 공백으로 구분하여 출력한다.

import random

words = ["학습", "컴퓨터", "마우스", "인공지능", "프로그래밍", "파이썬", "데이터"]
selected_words = random.sample(words, 3)

print(" ".join(selected_words))