# 문제: 1부터 100 사이 정수 중에서 3의 배수의 개수를 리스트 함축과 내장 함수를 이용하여 세는 프로그램을 작성하라.
# 설계:
# - 리스트 함축을 사용하여 1부터 100 사이의 정수 중 3의 배수만 포함하는 리스트를 생성한다.
# - len() 함수를 사용하여 리스트의 요소 개수를 구한다.
# - 구한 개수를 지정된 형식으로 출력한다.

count = len([x for x in range(1, 101) if x % 3 == 0])
print(f"3의 배수의 개수 = {count}")
      