# 문제: eval() 함수를 사용하여 사용자가 어떤 문자열을 입력하더라도 오류를 일으키지 않고 정수나 실수로 변환하는 코드를 작성해보자.
# 설계:
# - input() 함수로 사용자로부터 문자열 입력을 받는다.
# - eval() 함수를 이용해 입력된 문자열을 파이썬 표현식으로 평가하여 알맞은 숫자(정수 또는 실수)로 변환한다.
# - 변환된 값을 출력한다.

user_input = input("정수나 실수를 입력하시오: ")
result = eval(user_input)
print(result)
