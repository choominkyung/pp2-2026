# 문제: 람다식을 사용하여 튜플을 정렬하는 프로그램을 작성하라.
# 설계:
# - 과목명과 점수가 포함된 튜플들의 리스트를 생성한다.
# - sorted() 함수의 key 매개변수에 람다식을 전달하여 튜플의 두 번째 요소(점수)를 기준으로 정렬한다.
# - 원래의 리스트와 정렬된 리스트를 출력한다.

original_list = [('국어', 88), ('수학', 90), ('영어', 99), ('자연', 82)]
sorted_list = sorted(original_list, key=lambda x: x[1])

print(f"원래의 리스트:\n{original_list}")
print(f"정렬된 리스트:\n{sorted_list}")
